// Creates a demo project ("Pillie demo") with ~60 days of realistic, randomly generated
// activity so every screen has something to show. Safe to re-run: it replaces the demo project.
//
//   npm run db:seed
import { randomBytes, randomUUID } from "node:crypto";
import postgres from "postgres";
import { DB_CONFIG_MISSING, connect, dbConfig } from "./db-config.mjs";

if (!dbConfig()) {
  console.error(DB_CONFIG_MISSING);
  process.exit(1);
}
const sql = connect(postgres, { max: 1, onnotice: () => {} });

const DAY = 86_400_000;
const DAYS = 60;
const SLUG = "pillie-demo";

// Small deterministic PRNG so the demo looks the same each run.
let seed = 42;
const rand = () => ((seed = (seed * 1664525 + 1013904223) % 4294967296) / 4294967296);
const pick = (arr) => arr[Math.floor(rand() * arr.length)];
const chance = (p) => rand() < p;

const versionAt = (t) => {
  const daysAgo = (Date.now() - t) / DAY;
  if (daysAgo > 40) return "1.0.0";
  if (daysAgo > 18) return "1.1.0";
  return "1.2.0";
};

try {
  await sql`delete from projects where slug = ${SLUG}`;
  const [project] = await sql`
    insert into projects (name, slug, description, platform, timezone, ingest_key, onboarding_steps, onboarding_window_days)
    values ('Pillie (demo)', ${SLUG}, 'Medication reminders. Demo data generated by scripts/seed.mjs.', 'cross-platform', 'Asia/Manila',
            ${"ac_demo_" + randomBytes(12).toString("base64url")},
            ${["onboarding_started", "onboarding_step step=goals", "onboarding_step step=reminders", "onboarding_step step=notifications", "onboarding_completed"]},
            7)
    returning id
  `;

  const events = [];
  const users = new Map();
  const add = (userId, name, t, properties = {}, platform) => {
    const v = versionAt(t);
    events.push({
      project_id: project.id,
      user_id: userId,
      name,
      properties,
      app_version: v,
      platform,
      message_id: randomUUID(),
      occurred_at: new Date(t),
    });
    const u = users.get(userId);
    if (!u) users.set(userId, { first: t, last: t, count: 1, v, platform });
    else {
      u.count++;
      u.first = Math.min(u.first, t);
      if (t >= u.last) Object.assign(u, { last: t, v });
    }
  };

  const now = Date.now();
  for (let d = DAYS; d >= 0; d--) {
    // Installs grow over time, with a dip mid-way.
    const installs = Math.round(6 + (DAYS - d) * 0.35 + (d > 20 && d < 28 ? -4 : 0) + rand() * 4);
    for (let i = 0; i < installs; i++) {
      const id = randomUUID();
      const platform = chance(0.58) ? "ios" : "android";
      let t = now - d * DAY + Math.floor(rand() * DAY * 0.9) - DAY;
      if (t > now) t = now - 60_000;

      add(id, "app_open", t, {}, platform);
      add(id, "onboarding_started", t + 5_000, { source: pick(["app_store", "play_store", "friend", "tiktok", "app_store"]) }, platform);
      let step = t + 20_000;
      if (!chance(0.86)) continue;
      add(id, "onboarding_step", step, { step: "goals", goal: [pick(["never_miss", "track_refills", "family"]), ...(chance(0.4) ? ["build_habit"] : [])] }, platform);
      step += 25_000;
      if (!chance(0.72)) continue;
      add(id, "onboarding_step", step, { step: "reminders", reminder_time: pick(["morning", "morning", "noon", "evening", "night"]), pills_per_day: pick([1, 1, 2, 2, 3]) }, platform);
      step += 15_000;
      if (!chance(0.88)) continue;
      add(id, "onboarding_step", step, { step: "notifications", allowed: chance(0.78) }, platform);
      add(id, "onboarding_completed", step + 2_000, {}, platform);

      // Returning usage: completed users come back with decaying probability.
      const loyal = rand();
      for (let k = 1; k <= d; k++) {
        const p = loyal > 0.6 ? 0.7 : loyal > 0.3 ? 0.35 / Math.sqrt(k) : 0.15 / k;
        if (!chance(p)) continue;
        const tk = t + k * DAY + Math.floor(rand() * 3_600_000);
        if (tk > now) break;
        add(id, "app_open", tk, {}, platform);
        const doses = 1 + Math.floor(rand() * 3);
        for (let j = 0; j < doses; j++) add(id, "dose_logged", tk + j * 60_000, { on_time: chance(0.8) }, platform);
        if (chance(0.05)) add(id, "refill_reminder_set", tk + 300_000, {}, platform);
      }
    }
  }

  for (let i = 0; i < events.length; i += 2000) {
    await sql`insert into events ${sql(events.slice(i, i + 2000))}`;
  }
  const userRows = [...users].map(([id, u]) => ({
    project_id: project.id,
    id,
    traits: { goal_count: Math.ceil(rand() * 2) },
    app_version: u.v,
    platform: u.platform,
    event_count: u.count,
    first_seen_at: new Date(u.first),
    last_seen_at: new Date(u.last),
  }));
  for (let i = 0; i < userRows.length; i += 2000) {
    await sql`insert into app_users ${sql(userRows.slice(i, i + 2000))}`;
  }

  console.log(`seeded "${SLUG}": ${users.size} users, ${events.length} events`);
} finally {
  await sql.end();
}
